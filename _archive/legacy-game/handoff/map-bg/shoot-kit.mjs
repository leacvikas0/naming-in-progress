import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "msedge", headless: true, args: ["--use-angle=default","--enable-unsafe-swiftshader"] });
const p = await b.newPage({ viewport: { width: 1400, height: 800 } });
p.on("pageerror", e => console.log("[pageerror]", String(e).slice(0,600)));
p.on("console", m => { if (m.type()==="error") console.log("[c]", m.text().slice(0,400)); });
await p.goto("http://127.0.0.1:4173/game/handoff/map-bg/preview.html", { waitUntil: "load" });
await p.waitForTimeout(6000);
const st = await p.evaluate(() => window.__meadow ? window.__meadow.bg.stats : null);
console.log("stats:", JSON.stringify(st));
await p.evaluate(() => { window.__meadow.bg.setPostEnabled(false); });
await p.waitForTimeout(800);
await p.screenshot({ path: "C:/Users/silen/projects/kilo-3d-kit/game/handoff/map-bg/shots/kit-01-gameplay.png" });
await p.evaluate(() => window.__meadow.applyView("aerial"));
await p.waitForTimeout(900);
await p.screenshot({ path: "C:/Users/silen/projects/kilo-3d-kit/game/handoff/map-bg/shots/kit-02-aerial.png" });
await b.close();
